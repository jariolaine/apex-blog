#!/usr/bin/env python3
"""Verify that locally maintained APEXlang files match the DEV export.

Supporting Objects SQL is generated by BUILD_API; application static files
are edited/built in the repository. Neither may silently diverge from the
files embedded in the SQL application release exported from DEV.
"""

import argparse
from pathlib import Path
import sys


# (human-friendly name, path inside an APEXlang application, SQL files only?)
PROTECTED = (
    ("Supporting Objects SQL", Path("supporting-objects"), True),
    ("Static application files", Path("shared-components/static-files"), False),
)


def inventory(app: Path, directory: Path, sql_only: bool) -> dict[Path, bytes]:
    root = app / directory
    if root.is_symlink():
        raise ValueError(f"Symlink is not permitted: {root}")
    if not root.exists():
        return {}
    if not root.is_dir():
        raise ValueError(f"Expected a directory: {root}")
    result = {}
    for file in root.rglob("*"):
        if file.is_symlink():
            raise ValueError(f"Symlink is not permitted: {file}")
        if file.is_file() and (not sql_only or file.suffix.lower() == ".sql"):
            result[file.relative_to(app)] = file.read_bytes()
    return result


def check(repository_app: Path, exported_app: Path) -> int:
    failed = False
    for label, directory, sql_only in PROTECTED:
        local = inventory(repository_app, directory, sql_only)
        dev = inventory(exported_app, directory, sql_only)
        differences = [
            (path, "missing from DEV" if path not in dev else
             "missing from repository" if path not in local else "content differs")
            for path in sorted(local.keys() | dev.keys())
            if local.get(path) != dev.get(path)
        ]
        if differences:
            failed = True
            print(f"ERROR: {label} differ between the repository and DEV:", file=sys.stderr)
            for path, reason in differences[:30]:
                print(f"  {path.as_posix()} ({reason})", file=sys.stderr)
            if len(differences) > 30:
                print(f"  ... and {len(differences) - 30} more", file=sys.stderr)
    if failed:
        print("Review the differences. If the repository files are correct, "
              "run 'make sync-dev' to update DEV, then rerun 'make build'. "
              "If DEV is authoritative, review and update the repository files explicitly.",
              file=sys.stderr)
    return int(failed)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repository_app", type=Path)
    parser.add_argument("exported_app", type=Path)
    args = parser.parse_args()
    try:
        return check(args.repository_app, args.exported_app)
    except (OSError, ValueError) as error:
        print(f"ERROR: Could not verify protected files: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
